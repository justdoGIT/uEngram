"""Collect appendix tables from the study modules and render them as Markdown."""
from __future__ import annotations

import html
import importlib
from pathlib import Path

GROUPS = (
    ("synth_cmapss", "Synthetic streams and CMAPSS"),
    ("metropt_care_scania", "MetroPT, CARE, and SCANIA"),
    ("skab", "SKAB event studies"),
    ("model_gates", "Encoder, teacher, and role gates"),
    ("v8_chain", "MetroPT alarm-definition campaign (final v8)"),
    ("capsule", "Persistence and crash recovery"),
)
OUTCOMES = ("positive", "mixed", "null", "negative")
LABELS = {"positive": "Positive", "mixed": "Mixed", "null": "Null", "negative": "Negative"}


def collect(repo: Path) -> list[tuple[str, str, list[dict]]]:
    """Return (module, heading, tables) for every group, validating the contract."""
    groups = []
    for module, heading in GROUPS:
        tables = importlib.import_module(f"results_appendix.{module}").build(repo)
        for table in tables:
            if table["outcome"] not in OUTCOMES:
                raise ValueError(f"{module}: bad outcome {table['outcome']!r}")
            width = len(table["columns"])
            for row in table["rows"]:
                if len(row) != width:
                    raise ValueError(f"{module}: {table['title']!r} row width {len(row)} != {width}")
        groups.append((module, heading, tables))
    return groups


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def header(text: str) -> str:
    """Column names come straight from result keys; show them as words."""
    words = cell(text).replace("_", " ")
    return words[:1].upper() + words[1:]


def tally(groups) -> dict[str, dict[str, int]]:
    counts = {heading: {o: 0 for o in OUTCOMES} for _, heading, _ in groups}
    for _, heading, tables in groups:
        for table in tables:
            counts[heading][table["outcome"]] += 1
    return counts


def render(groups, figure_line: str) -> str:
    counts = tally(groups)
    total = {o: sum(c[o] for c in counts.values()) for o in OUTCOMES}
    n_tables = sum(total.values())
    out = [
        "## Complete Results Ledger",
        "",
        f"These supplementary tables are generated from files in `results/` ({n_tables} tables), "
        "excluding an empty CMAPSS file and a SCANIA score archive that repeats the validation JSON. "
        "Each table is generated by `scripts/build_results_appendix.py` directly from the JSON "
        "and JSONL it cites, so no value is typed by hand. Campaigns that were repeated under "
        "version labels appear once, as their final version; superseded runs are omitted. Every "
        "table carries an outcome tag, and negative and null results are kept beside the positive ones.",
        "",
        "**How outcomes are assigned.** *Positive*: the tested change beat its in-study baseline "
        "on the primary metric with no guard metric failing. *Negative*: it missed its own goal "
        "or did worse than its baseline. *Null*: it was indistinguishable from the baseline. "
        "*Mixed*: some metrics or settings improved while others regressed. The tag is an "
        "editorial label on the table, not a computed statistic; the numbers beneath it are.",
        "",
        figure_line,
        "",
        "**Table A0.** Outcome count per result group.",
        "",
        "| Group | " + " | ".join(LABELS[o] for o in OUTCOMES) + " |",
        "|---|" + "---:|" * len(OUTCOMES),
    ]
    for heading, c in counts.items():
        out.append(f"| {heading} | " + " | ".join(str(c[o]) for o in OUTCOMES) + " |")
    out.append("| **All groups** | " + " | ".join(f"**{total[o]}**" for o in OUTCOMES) + " |")
    out.append("")
    number = 0
    for index, (_, heading, tables) in enumerate(groups, 1):
        out += [f"### A.{index} {heading}", ""]
        for table in tables:
            number += 1
            tag = f'<span class="outcome {table["outcome"]}">{LABELS[table["outcome"]]}</span>'
            out += [f"**Table A{number}.** {tag}{table['title']}", ""]
            out.append("| " + " | ".join(header(c) for c in table["columns"]) + " |")
            out.append("|" + "---|" * len(table["columns"]))
            out += ["| " + " | ".join(cell(c) for c in row) + " |" for row in table["rows"]]
            out += [
                "",
                '<p class="table-note"><b>Source</b> '
                f"<code>{html.escape(table['source'])}</code>. {html.escape(table['note'])}</p>",
                "",
            ]
    return "\n".join(out).rstrip() + "\n"
